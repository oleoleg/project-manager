import os
from PIL import Image, ImageDraw

# Создаем изображение 32x32 с прозрачным фоном
img = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
draw = ImageDraw.Draw(img)

# 1. Задний план: абстрактная цветная диаграмма Ганта (полосы задач)
# 1-я полоса (ярко-синяя)
draw.rectangle([4, 4, 20, 7], fill=(59, 130, 246, 200)) 
# 2-я полоса (зеленая)
draw.rectangle([12, 9, 28, 12], fill=(16, 185, 129, 200)) 
# 3-я полоса (акцентированная оранжевая)
draw.rectangle([2, 14, 10, 16], fill=(249, 115, 22, 140))

# 2. Передний план: Четкие белые буквы P и M (высота 14 пикселей, толщина линий 2px)

# --- Буква P ---
# Вертикальная стойка (x:3..4, y:14..28)
draw.rectangle([3, 14, 4, 28], fill=(255, 255, 255, 255))
# Верхняя петля буквы P
draw.rectangle([5, 14, 11, 15], fill=(255, 255, 255, 255))
draw.rectangle([10, 16, 11, 21], fill=(255, 255, 255, 255))
draw.rectangle([5, 20, 11, 21], fill=(255, 255, 255, 255))

# --- Буква M ---
# Левая стойка (x:14..15, y:14..28)
draw.rectangle([14, 14, 15, 28], fill=(255, 255, 255, 255))
# Правая стойка (x:25..26, y:14..28)
draw.rectangle([25, 14, 26, 28], fill=(255, 255, 255, 255))
# Внутренние диагональные линии («птичка» по центру)
draw.rectangle([16, 16, 17, 18], fill=(255, 255, 255, 255))
draw.rectangle([18, 19, 21, 21], fill=(255, 255, 255, 255))
draw.rectangle([22, 16, 24, 18], fill=(255, 255, 255, 255))
draw.point((20, 22), fill=(255, 255, 255, 255))

# Определяем папку, в которой лежит сам скрипт, и сохраняем иконку туда
script_dir = os.path.dirname(os.path.abspath(__file__))
img.save(os.path.join(script_dir, "icon.ico"), format="ICO", sizes=[(32, 32)])
print("Иконка успешно создана в папке assets!")
