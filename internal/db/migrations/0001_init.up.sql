-- =========================================================
-- 000001_init — базовая схема Project Manager (актуальная)
-- =========================================================

-- ---------------------------------------------------------
-- Пользователи и роли
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS roles (
    code        TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    description TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            TEXT NOT NULL UNIQUE,
    full_name           TEXT NOT NULL,
    password_hash       TEXT NOT NULL,
    role_code           TEXT NOT NULL REFERENCES roles(code),
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    theme               TEXT NOT NULL DEFAULT 'light',
    hide_financials     BOOLEAN NOT NULL DEFAULT FALSE,
    check_contract_path BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT users_theme_check CHECK (theme = ANY (ARRAY['light'::text, 'dark'::text]))
);

-- ---------------------------------------------------------
-- Контрагенты
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS counterparties (
    id               TEXT PRIMARY KEY,
    name             TEXT NOT NULL,
    partner          TEXT,
    short_name       TEXT,
    address_actual   TEXT,
    address_legal    TEXT,
    url_workplace    TEXT,
    url_servicework  TEXT,
    url_salesprep    TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT counterparties_id_format CHECK (id ~ '^[0-9]{4}$')
);

-- ---------------------------------------------------------
-- Договоры
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS contracts (
    id                      TEXT PRIMARY KEY,
    contract_number         TEXT NOT NULL,
    contract_date           DATE,
    work_name               TEXT NOT NULL,
    responsible_person      TEXT,
    status_code             SMALLINT NOT NULL,
    counterparty_id         TEXT NOT NULL REFERENCES counterparties(id),
    workshop                TEXT,
    project_url             TEXT,
    procurement_card_status TEXT,
    extra_details           TEXT,
    finplan_status          TEXT,
    plan_schedule_status    TEXT,
    short_name              TEXT NOT NULL,
    contract_type           TEXT NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    responsible_user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    server_path             TEXT NOT NULL DEFAULT '',
    CONSTRAINT contracts_id_format CHECK (id ~ '^[0-9]{4}(-[A-Za-zА-Яа-я0-9]{1,5})?$')
);

-- ---------------------------------------------------------
-- Ответственные лица
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS contract_assignees (
    contract_id TEXT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (contract_id, user_id)
);

-- ---------------------------------------------------------
-- Этапы договоров
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS stages (
    guid                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contract_id          TEXT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    row_order            INTEGER NOT NULL DEFAULT 0,
    stage_number         TEXT NOT NULL,
    name                 TEXT NOT NULL,
    cost                 NUMERIC(15,2) NOT NULL DEFAULT 0,
    closed_by_acts       NUMERIC(15,2) NOT NULL DEFAULT 0,
    vat_percent          NUMERIC(5,2) NOT NULL DEFAULT 0,
    advance_percent      NUMERIC(5,2) NOT NULL DEFAULT 0,
    start_conditions     TEXT,
    end_conditions       TEXT,
    close_date_plan      DATE,
    responsible_person   TEXT,
    status_code          SMALLINT NOT NULL,
    work_kind            TEXT NOT NULL,
    note                 TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_by_acts_manual BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT stages_advance_range CHECK (advance_percent >= 0 AND advance_percent <= 100),
    CONSTRAINT stages_vat_range CHECK (vat_percent >= 0 AND vat_percent <= 100),
    CONSTRAINT unique_contract_stage_number UNIQUE (contract_id, stage_number)
);

-- ---------------------------------------------------------
-- Затраты этапов
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS stage_costs (
    guid               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    stage_guid         UUID NOT NULL REFERENCES stages(guid) ON DELETE CASCADE,
    work_kind          TEXT NOT NULL,
    cost               NUMERIC(15,2) NOT NULL DEFAULT 0,
    fot_plan           NUMERIC(15,2) NOT NULL DEFAULT 0,
    labor_days         NUMERIC(10,2) NOT NULL DEFAULT 0,
    rate_per_day       NUMERIC(15,2) NOT NULL DEFAULT 0,
    travel_expenses    NUMERIC(15,2) NOT NULL DEFAULT 0,
    equipment_sale     NUMERIC(15,2) NOT NULL DEFAULT 0,
    equipment_cost     NUMERIC(15,2) NOT NULL DEFAULT 0,
    subcontract        NUMERIC(15,2) NOT NULL DEFAULT 0,
    commission         NUMERIC(15,2) NOT NULL DEFAULT 0,
    other_expenses     NUMERIC(15,2) NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    calc_field         TEXT NOT NULL DEFAULT '',
    CONSTRAINT stage_costs_work_kind_not_complex CHECK (work_kind <> 'complex')
);

-- ---------------------------------------------------------
-- Акты
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS acts (
    guid                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    kind                  TEXT NOT NULL,
    kind_custom           TEXT NOT NULL DEFAULT '',
    name                  TEXT NOT NULL,
    amount                NUMERIC(15,2) NOT NULL DEFAULT 0,
    sign_date             DATE,
    file_path             TEXT NOT NULL DEFAULT '',
    note                  TEXT NOT NULL DEFAULT '',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    distribution_expanded BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS act_stages (
    act_guid    UUID NOT NULL REFERENCES acts(guid) ON DELETE CASCADE,
    stage_guid  UUID NOT NULL REFERENCES stages(guid) ON DELETE CASCADE,
    amount      NUMERIC(15,2) NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (act_guid, stage_guid)
);

CREATE TABLE IF NOT EXISTS act_attachments (
    guid        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    act_guid    UUID NOT NULL REFERENCES acts(guid) ON DELETE CASCADE,
    kind        TEXT NOT NULL,
    kind_custom TEXT NOT NULL DEFAULT '',
    name        TEXT NOT NULL,
    file_path   TEXT NOT NULL DEFAULT '',
    note        TEXT NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Бюджет (План и Факт)
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS budget_settings (
    contract_id           TEXT PRIMARY KEY REFERENCES contracts(id) ON DELETE CASCADE,
    project_start_date    DATE NOT NULL,
    project_end_date      DATE,
    payment_delay_days    INTEGER NOT NULL DEFAULT 20,
    equip_payment_percent NUMERIC(5,2) DEFAULT 0,
    equip_payment_delay   INTEGER DEFAULT 2,
    overhead_rate         NUMERIC(10,4) NOT NULL DEFAULT 1.2,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS budget_plan_snapshots (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contract_id          TEXT NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by           BIGINT REFERENCES users(id),
    settings             JSONB,
    is_active            BOOLEAN NOT NULL DEFAULT FALSE,
    note                 TEXT,
    approved_by          BIGINT REFERENCES users(id),
    approved_at          TIMESTAMPTZ,
    stage_costs_snapshot JSONB DEFAULT '[]'::jsonb,
    stage_data_snapshot  JSONB DEFAULT '[]'::jsonb,
    plan_data_snapshot   JSONB DEFAULT '[]'::jsonb
);

CREATE TABLE IF NOT EXISTS budget_plan_lines (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    work_kind      VARCHAR(50),
    name           TEXT NOT NULL,
    operation_date DATE NOT NULL,
    delay_days     INTEGER NOT NULL DEFAULT 0,
    payment_date   DATE NOT NULL,
    income         NUMERIC(15,2) NOT NULL DEFAULT 0,
    expense        NUMERIC(15,2) NOT NULL DEFAULT 0,
    operation_type VARCHAR(100) NOT NULL,
    note           TEXT,
    contract_id    VARCHAR(255) NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    stage_number   VARCHAR(50),
    stage_name     VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS budget_fact_lines (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    contract_id    VARCHAR(16) NOT NULL REFERENCES contracts(id) ON DELETE CASCADE,
    plan_line_id   UUID REFERENCES budget_plan_lines(id) ON DELETE SET NULL,
    work_kind      VARCHAR(50),
    name           TEXT NOT NULL,
    operation_date DATE NOT NULL,
    payment_date   DATE NOT NULL,
    operation_type VARCHAR(100) NOT NULL,
    fact_income    NUMERIC(15,2) NOT NULL DEFAULT 0,
    fact_expense   NUMERIC(15,2) NOT NULL DEFAULT 0,
    is_confirmed   BOOLEAN NOT NULL DEFAULT FALSE,
    is_manual_edit BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    delay_days     INTEGER NOT NULL DEFAULT 0,
    stage_number   VARCHAR(50),
    stage_name     VARCHAR(255)
);

-- ---------------------------------------------------------
-- Настройки приложения
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_settings (
    key        TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================================
-- ИНДЕКСЫ
-- =========================================================
CREATE INDEX IF NOT EXISTS idx_act_attachments_act         ON act_attachments(act_guid);
CREATE INDEX IF NOT EXISTS idx_act_stages_stage            ON act_stages(stage_guid);
CREATE INDEX IF NOT EXISTS idx_acts_file_path              ON acts(file_path);
CREATE INDEX IF NOT EXISTS idx_acts_sign_date              ON acts(sign_date);
CREATE INDEX IF NOT EXISTS idx_budget_fact_lines_stage_num ON budget_fact_lines(contract_id, stage_number);
CREATE INDEX IF NOT EXISTS idx_budget_plan_lines_contract_id ON budget_plan_lines(contract_id);
CREATE INDEX IF NOT EXISTS idx_budget_plan_lines_stage_num ON budget_plan_lines(contract_id, stage_number);
CREATE INDEX IF NOT EXISTS idx_budget_plan_snapshots_contract ON budget_plan_snapshots(contract_id);
CREATE INDEX IF NOT EXISTS idx_contract_assignees_user     ON contract_assignees(user_id);
CREATE INDEX IF NOT EXISTS idx_contracts_counterparty      ON contracts(counterparty_id);
CREATE INDEX IF NOT EXISTS idx_contracts_responsible       ON contracts(responsible_user_id);
CREATE INDEX IF NOT EXISTS idx_contracts_status            ON contracts(status_code);
CREATE INDEX IF NOT EXISTS idx_stage_costs_stage           ON stage_costs(stage_guid);
CREATE INDEX IF NOT EXISTS idx_stages_contract             ON stages(contract_id);
CREATE INDEX IF NOT EXISTS idx_stages_order                ON stages(contract_id, row_order);